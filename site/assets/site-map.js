/* The briefing map (2026-11-16).

   The home page's briefing lists 18 sites and how hot a normal afternoon is at
   each in the reader's month. A list cannot show where they are, and where is
   half the answer: the hot ones are the southern ones. This puts each site at
   its own coordinates (assets/egypt-sites.svg, generated by
   backend/pipeline/build_site_map.py from the same file the briefing reads),
   colours it by the same heat band as its card, and when the briefing is
   reached brings the dots in from north to south. When the reader changes
   their dates the dots are recoloured and come in again, so the change shows.

   The rules this keeps:
   - Without JavaScript the map is a plain image: every site in its place, gold.
   - The motion is opacity and transform only, and none of it runs for readers
     who asked for reduced motion (site-map.css): they get the coloured map at
     once.
   - If the map file cannot be fetched or parsed, the image stays.
   home.js hands over the figures with an `egybi:heat` event, and leaves the
   last one on window.EGYBI.heat in case this script is late. */
(function () {
  'use strict';
  var fig = document.getElementById('siteMap');
  var T = window.EGYBI && window.EGYBI.trip;
  if (!fig || !T || !window.fetch || !window.DOMParser) return;
  var img = fig.querySelector('img');
  if (!img) return;
  var reduce = window.matchMedia && window.matchMedia('(prefers-reduced-motion: reduce)').matches;
  var svg = null, last = window.EGYBI.heat || null, seen = false;

  function setText(id, text) { var e = document.getElementById(id); if (e) e.textContent = text; }

  function paint(d) {
    last = d;
    if (!svg || !d || !d.sites) return;
    var byKey = {}, rows = [];
    d.sites.forEach(function (s) { byKey[s.key] = s; });
    Array.prototype.forEach.call(svg.querySelectorAll('circle.s'), function (c) {
      var s = byKey[c.getAttribute('data-key')];
      var m = s ? (T.monthRow(s, d.month) || {}) : {};
      var bd = T.band(m.t_daily_max);
      c.setAttribute('fill', bd ? bd.colour : '#C9A227');
      var t = c.querySelector('title');
      if (s && t) {
        t.textContent = s.name + (m.t_daily_max == null ? '' :
          ': ' + Math.round(m.t_daily_max) + ' °C on a normal ' + T.MONTHS[d.month] + ' afternoon');
      }
      if (s && m.t_daily_max != null) rows.push({ name: s.name, t: m.t_daily_max });
    });
    if (rows.length > 1) {
      rows.sort(function (a, b) { return a.t - b.t; });
      var lo = rows[0], hi = rows[rows.length - 1];
      setText('siteMapSummary', 'In ' + T.MONTHS[d.month] + ', a normal afternoon runs from ' +
        Math.round(lo.t) + ' °C at ' + lo.name + ' to ' + Math.round(hi.t) + ' °C at ' + hi.name + '. ');
    }
    play();
  }

  // Bring the dots in from north to south (their data-order, set by the
  // generator from latitude). Restarting the class replays it after a date change.
  function play() {
    if (reduce || !svg || !seen) return;
    svg.classList.remove('is-waiting', 'is-drawing');
    void svg.getBoundingClientRect();
    svg.classList.add('is-drawing');
  }

  function watch() {
    if (reduce) { seen = true; return; }
    if (!('IntersectionObserver' in window)) { seen = true; play(); return; }
    var io = new IntersectionObserver(function (es) {
      if (es.some(function (e) { return e.isIntersecting; })) { io.disconnect(); seen = true; play(); }
    }, { threshold: 0.35 });
    io.observe(fig);
  }

  document.addEventListener('egybi:heat', function (e) { paint(e.detail); });

  fetch(img.getAttribute('src')).then(function (r) {
    if (!r.ok) throw new Error('map ' + r.status);
    return r.text();
  }).then(function (text) {
    var doc = new DOMParser().parseFromString(text, 'image/svg+xml');
    var root = doc.documentElement;
    if (!root || root.nodeName !== 'svg' || doc.getElementsByTagName('parsererror').length) return;
    root = document.importNode(root, true);
    Array.prototype.forEach.call(root.querySelectorAll('script, foreignObject'), function (n) { n.remove(); });
    root.setAttribute('class', 'site-map-svg' + (reduce ? '' : ' is-waiting'));
    root.setAttribute('aria-label', img.getAttribute('alt') || 'Map of Egypt with the measured sites');
    Array.prototype.forEach.call(root.querySelectorAll('circle.s'), function (c) {
      c.style.setProperty('--i', c.getAttribute('data-order') || '0');
    });
    img.replaceWith(root);
    svg = root;
    watch();
    if (last) paint(last);
  }).catch(function () { /* the image stays: every site still in its place */ });
})();
