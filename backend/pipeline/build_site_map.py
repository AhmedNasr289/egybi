"""
Build the briefing map: the outline of Egypt with the 18 measured sites.

WHAT IT IS FOR. The home page's briefing lists 18 sites and how hot a normal
afternoon is at each in the reader's month. A list cannot show WHERE they are,
and where is half the answer: the hot ones are the southern ones. This map
puts each site at its own coordinates so the page can colour it by the same
heat band as its card (assets/site-map.js) and bring the dots in from north to
south as the briefing is reached.

WHERE THE NUMBERS COME FROM. Nothing is drawn by hand:
  - the outline is the national border dissolved from egy_adm1_simplified.geojson
    by the same code as the flag (build_flag.py: rings, dissolve, simplify), so it
    is the geoBoundaries geometry the Atlas renders (CC BY 4.0);
  - each dot is projected from the lat/lon in site/data/visit-climate.json, the
    file the briefing reads, so a site cannot sit in one place on the map and
    carry another site's figure.

The projection is build_flag.py's: equirectangular with x scaled by the cosine
of the mean latitude. Without JavaScript the page shows this file as an image:
every dot gold, every site still in its place.

Run:  python backend/pipeline/build_site_map.py
"""
import json
import math
import os
import sys

HERE = os.path.dirname(os.path.abspath(__file__))
sys.path.insert(0, HERE)
import build_flag as bf  # noqa: E402  (rings, dissolve, simplify; one source for the outline)

SRC = bf.SRC
SITES = os.path.join(HERE, "..", "..", "site", "data", "visit-climate.json")
OUT = os.path.join(HERE, "..", "..", "site", "assets", "egypt-sites.svg")

VIEW_H = 400.0
TOLERANCE = 1.2         # view units; the map is drawn at about 300-400 px tall
MIN_RING_SPAN = 3.0
PRECISION = 1
DOT_R = 6.5

LAND = "#E9DDBF"        # papyrus, a shade darker than the briefing's surface
EDGE = "#8A7549"
DOT = "#C9A227"         # --gold: the no-JS colour
DOT_EDGE = "#241F1A"


def esc(s):
    return (str(s).replace("&", "&amp;").replace("<", "&lt;")
            .replace(">", "&gt;").replace('"', "&quot;"))


def main():
    with open(SRC, "r", encoding="utf-8") as f:
        geo = json.load(f)
    all_rings = []
    for feat in geo["features"]:
        all_rings.extend(list(bf.rings(feat["geometry"])))
    exterior, internal = bf.dissolve(all_rings)
    if not internal or not exterior:
        sys.exit("The dissolve failed on %s; see build_flag.py. Refusing to write a map."
                 % os.path.basename(SRC))

    with open(SITES, "r", encoding="utf-8") as f:
        sites = json.load(f)["sites"]
    if len(sites) < 10:
        sys.exit("visit-climate.json lists %d sites; expected the 18 measured ones." % len(sites))

    lons = [p[0] for r in exterior for p in r]
    lats = [p[1] for r in exterior for p in r]
    lon0, lon1 = min(lons), max(lons)
    lat0, lat1 = min(lats), max(lats)
    kx = math.cos(math.radians((lat0 + lat1) / 2))
    scale = VIEW_H / (lat1 - lat0)
    view_w = (lon1 - lon0) * kx * scale

    def project(lon, lat):
        return ((lon - lon0) * kx * scale, (lat1 - lat) * scale)

    parts = []
    for ring in exterior:
        pts = [project(lon, lat) for lon, lat in ring]
        xs = [p[0] for p in pts]
        ys = [p[1] for p in pts]
        if max(xs) - min(xs) < MIN_RING_SPAN and max(ys) - min(ys) < MIN_RING_SPAN:
            continue
        pts = bf.simplify(pts, TOLERANCE)
        if len(pts) < 3:
            continue
        parts.append("M" + " ".join("%.*f,%.*f" % (PRECISION, x, PRECISION, y) for x, y in pts) + "Z")

    # North to south: the order the page brings the dots in. Ties (none today)
    # fall back to the key, so the file is the same on every run.
    order = sorted(sites, key=lambda s: (-s["lat"], s["key"]))
    dots = []
    for i, s in enumerate(order):
        x, y = project(s["lon"], s["lat"])
        if not (0 <= x <= view_w and 0 <= y <= VIEW_H):
            sys.exit("%s projects outside the map (%.1f, %.1f); its coordinates are wrong."
                     % (s["key"], x, y))
        dots.append(
            '<circle class="s" data-key="%s" data-order="%d" cx="%.1f" cy="%.1f" r="%.1f">'
            '<title>%s</title></circle>' % (esc(s["key"]), i, x, y, DOT_R, esc(s["name"])))

    svg = (
        '<svg xmlns="http://www.w3.org/2000/svg" viewBox="0 0 %.1f %.1f" '
        'role="img" aria-label="Map of Egypt with the %d sites measured in the briefing">\n'
        '<title>The %d measured sites</title>\n'
        '<!-- Generated by backend/pipeline/build_site_map.py from egy_adm1_simplified.geojson\n'
        '     (geoBoundaries.org EGY ADM1, CC BY 4.0, Runfola et al., 2020) and\n'
        '     site/data/visit-climate.json. Do not hand-edit: rerun the script. -->\n'
        '<path class="land" fill="%s" stroke="%s" stroke-width="1.6" stroke-linejoin="round" d="%s"/>\n'
        '<g class="sites" fill="%s" stroke="%s" stroke-width="1.6">\n%s\n</g>\n'
        '</svg>\n'
    ) % (view_w, VIEW_H, len(order), len(order), LAND, EDGE, "".join(parts),
         DOT, DOT_EDGE, "\n".join(dots))

    with open(OUT, "w", encoding="utf-8", newline="\n") as f:
        f.write(svg)
    print("Wrote %s: %d sites, %d bytes, viewBox 0 0 %.1f %.1f"
          % (os.path.relpath(OUT), len(order), len(svg.encode("utf-8")), view_w, VIEW_H))


if __name__ == "__main__":
    main()
